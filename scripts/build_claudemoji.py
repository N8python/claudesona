"""Import the Claudemoji set (one Claudesona per emoji) into the extension.

usage: python3 scripts/build_claudemoji.py <final set folder> [--height 384]

<final set folder> holds manifest.json (rows with "emoji", "file", "name") and the full-size
transparent PNGs it points to.

Writes:
  chrome-extension/assets/claudemoji/<key>.png   each avatar scaled to --height pixels tall
  chrome-extension/claudemoji.js                 the lookup table the content script reads

<key> is the emoji's code points in lower-case hex joined by "-", without variation selectors
(U+FE0F / U+FE0E), e.g. 1f601 for 😁 and 2764-200d-1f525 for ❤️‍🔥. content.js builds the same key
from whatever emoji is written in a <claude_... /> tag.
"""
import argparse
import json
from pathlib import Path

from PIL import Image

VARIATION_SELECTORS = {0xFE0F, 0xFE0E}


def key_of(emoji):
    return "-".join(f"{ord(ch):x}" for ch in emoji if ord(ch) not in VARIATION_SELECTORS)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("final", type=Path)
    parser.add_argument("--height", type=int, default=384, help="output height in pixels (shown at 128 CSS px)")
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[1]
    ext = root / "chrome-extension"
    out = ext / "assets" / "claudemoji"
    out.mkdir(parents=True, exist_ok=True)
    rows = json.loads((args.final / "manifest.json").read_text())

    table, total = {}, 0
    for row in rows:
        key = key_of(row["emoji"])
        if key in table:
            raise SystemExit(f"two avatars for {row['emoji']} ({key})")
        im = Image.open(args.final / row["file"]).convert("RGBA")
        width = round(im.width * args.height / im.height)
        # scale with premultiplied alpha so colour hidden under transparent pixels cannot bleed into the edge
        small = im.convert("RGBa").resize((width, args.height), Image.LANCZOS).convert("RGBA")
        dst = out / f"{key}.png"
        small.save(dst, optimize=True)
        total += dst.stat().st_size
        table[key] = row["name"]

    for stale in sorted(set(p.name for p in out.glob("*.png")) - {f"{k}.png" for k in table}):
        (out / stale).unlink()
        print("removed stale", stale)

    lines = [
        "// Generated by scripts/build_claudemoji.py. Do not edit by hand.",
        "// Emoji that have a Claudesona: key (code points, no variation selectors) -> emoji name.",
        "// The image for a key is assets/claudemoji/<key>.png.",
        "globalThis.SONA_CLAUDEMOJI = " + json.dumps(dict(sorted(table.items())), ensure_ascii=False, indent=2) + ";",
        "",
    ]
    (ext / "claudemoji.js").write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(table)} Claudemoji at {args.height}px tall, {total / 1e6:.1f} MB in {out.relative_to(root)}")


if __name__ == "__main__":
    main()
